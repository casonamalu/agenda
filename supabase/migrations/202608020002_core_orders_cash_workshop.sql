create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_sequence bigint generated by default as identity unique,
  client_id uuid not null references public.clients(id),
  source_appointment_id uuid references public.appointments(id) on delete set null,
  seller_id uuid references public.profiles(id) on delete set null,
  production_route public.production_route not null,
  status public.order_status not null default 'quote',
  product_name text not null,
  design_description text,
  sale_date date,
  event_date date,
  promised_delivery_date date,
  production_start_date date,
  planned_week_start date,
  actual_delivery_date date,
  planned_hours numeric(9,2) check (planned_hours is null or planned_hours >= 0),
  actual_hours numeric(9,2) check (actual_hours is null or actual_hours >= 0),
  variance_reason text,
  needs_fitting_1 boolean not null default true,
  needs_fitting_2 boolean not null default true,
  internal_notes text,
  created_by uuid not null default auth.uid() references public.profiles(id),
  updated_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_delivery_dates check (
    actual_delivery_date is null
    or promised_delivery_date is null
    or actual_delivery_date >= sale_date
  ),
  constraint orders_variance_reason check (
    actual_hours is null
    or planned_hours is null
    or actual_hours = planned_hours
    or nullif(trim(variance_reason), '') is not null
  )
);

