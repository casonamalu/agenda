create or replace function public.create_order_with_financials(
  p_client_id uuid,
  p_source_appointment_id uuid,
  p_production_route public.production_route,
  p_product_name text,
  p_design_description text,
  p_sale_date date,
  p_event_date date,
  p_promised_delivery_date date,
  p_gross_sale_amount numeric,
  p_discount_amount numeric,
  p_internal_notes text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid;
  v_tax numeric := coalesce((select (setting_value #>> '{}')::numeric from public.app_settings where setting_key = 'default_tax_rate'), 19);
  v_commission numeric := coalesce((select (setting_value #>> '{}')::numeric from public.app_settings where setting_key = 'default_sales_commission_rate'), 0);
  v_card_fee numeric := coalesce((select (setting_value #>> '{}')::numeric from public.app_settings where setting_key = 'default_card_fee_rate'), 0);
  v_hour_cost numeric := coalesce((select (setting_value #>> '{}')::numeric from public.app_settings where setting_key = 'workshop_hourly_cost'), 0);
begin
  if not public.can_manage_commercial() then
    raise exception 'Usuario no autorizado para crear pedidos';
  end if;
  if nullif(trim(p_product_name), '') is null then
    raise exception 'El producto o vestido es obligatorio';
  end if;
  if p_gross_sale_amount < 0 or p_discount_amount < 0 or p_discount_amount > p_gross_sale_amount then
    raise exception 'Los montos comerciales no son válidos';
  end if;
  if p_source_appointment_id is not null and not exists (
    select 1 from public.appointments
    where id = p_source_appointment_id and client_id = p_client_id
  ) then
    raise exception 'La cita de origen debe pertenecer a la misma cliente';
  end if;

  insert into public.orders(
    client_id, source_appointment_id, seller_id, production_route, status,
    product_name, design_description, sale_date, event_date,
    promised_delivery_date, internal_notes, created_by, updated_by
  ) values (
    p_client_id, p_source_appointment_id, auth.uid(), p_production_route, 'pending_planning',
    trim(p_product_name), nullif(trim(p_design_description), ''), p_sale_date,
    p_event_date, p_promised_delivery_date, nullif(trim(p_internal_notes), ''),
    auth.uid(), auth.uid()
  ) returning id into v_order_id;

  insert into public.order_financials(
    order_id, gross_sale_amount, discount_amount, tax_rate_snapshot,
    sales_commission_rate_snapshot, card_fee_rate_snapshot,
    workshop_hourly_cost_snapshot, created_by, updated_by
  ) values (
    v_order_id, p_gross_sale_amount, p_discount_amount, v_tax,
    v_commission, v_card_fee, v_hour_cost, auth.uid(), auth.uid()
  );

  if p_source_appointment_id is not null then
    update public.appointments
       set order_id = v_order_id, updated_by = auth.uid(), updated_at = now()
     where id = p_source_appointment_id;
  end if;

  return v_order_id;
end;
$$;

create or replace function public.reverse_order_payment(p_payment_id uuid, p_reason text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment public.order_payments%rowtype;
  v_reversal_id uuid;
begin
  if not public.can_manage_commercial() then raise exception 'Usuario no autorizado'; end if;
  if nullif(trim(p_reason), '') is null then raise exception 'El motivo es obligatorio'; end if;

  select * into v_payment from public.order_payments
  where id = p_payment_id and status = 'posted' for update;
  if not found then raise exception 'Pago no encontrado o ya reversado'; end if;

  insert into public.order_payments(
    order_id, amount, method, paid_at, reference, document_number,
    card_fee_rate_snapshot, status, reversal_of, notes, created_by
  ) values (
    v_payment.order_id, -v_payment.amount, v_payment.method, now(),
    v_payment.reference, v_payment.document_number, v_payment.card_fee_rate_snapshot,
    'reversed', v_payment.id, trim(p_reason), auth.uid()
  ) returning id into v_reversal_id;

  return v_reversal_id;
end;
$$;

create or replace function public.link_appointment_to_order(p_appointment_id uuid, p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_client uuid;
  v_appointment_client uuid;
begin
  if not public.is_internal_user() then raise exception 'Usuario no autorizado'; end if;
  select client_id into v_order_client from public.orders where id = p_order_id;
  select client_id into v_appointment_client from public.appointments where id = p_appointment_id;
  if v_order_client is null or v_appointment_client is null then
    raise exception 'Pedido o cita no encontrado';
  end if;
  if v_order_client <> v_appointment_client then
    raise exception 'La cita y el pedido deben pertenecer a la misma cliente';
  end if;
  update public.appointments
     set order_id = p_order_id, updated_by = auth.uid(), updated_at = now()
   where id = p_appointment_id;
end;
$$;

create or replace function public.reverse_cash_movement(p_movement_id uuid, p_reason text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_movement public.cash_movements%rowtype;
  v_reversal_id uuid;
begin
  if not public.can_manage_commercial() then raise exception 'Usuario no autorizado'; end if;
  if nullif(trim(p_reason), '') is null then raise exception 'El motivo es obligatorio'; end if;

  select * into v_movement from public.cash_movements
  where id = p_movement_id and status = 'posted' for update;
  if not found then raise exception 'Movimiento no encontrado o ya reversado'; end if;

  insert into public.cash_movements(
    order_id, direction, category, amount, method, occurred_at,
    description, reference, status, reversal_of, created_by
  ) values (
    v_movement.order_id,
    case when v_movement.direction = 'income' then 'expense'::public.cash_direction else 'income'::public.cash_direction end,
    'reverso', v_movement.amount, v_movement.method, now(),
    'Reverso: ' || trim(p_reason), v_movement.reference,
    'reversed', v_movement.id, auth.uid()
  ) returning id into v_reversal_id;

  return v_reversal_id;
end;
$$;

create or replace view public.order_financial_summary
with (security_invoker = true)
as
select
  o.id as order_id,
  o.order_sequence,
  f.gross_sale_amount,
  f.discount_amount,
  greatest(f.gross_sale_amount - f.discount_amount, 0) as final_sale_amount,
  case
    when f.tax_rate_snapshot = 0 then greatest(f.gross_sale_amount - f.discount_amount, 0)
    else greatest(f.gross_sale_amount - f.discount_amount, 0) / (1 + f.tax_rate_snapshot / 100)
  end as net_sales_amount,
  greatest(f.gross_sale_amount - f.discount_amount, 0)
    - case
        when f.tax_rate_snapshot = 0 then greatest(f.gross_sale_amount - f.discount_amount, 0)
        else greatest(f.gross_sale_amount - f.discount_amount, 0) / (1 + f.tax_rate_snapshot / 100)
      end as tax_amount,
  coalesce(sum(ci.total_cost) filter (where ci.phase = 'estimated'), 0) as estimated_material_cost,
  coalesce(sum(ci.total_cost) filter (where ci.phase = 'actual'), 0) as actual_material_cost,
  coalesce(o.planned_hours, 0) * f.workshop_hourly_cost_snapshot as estimated_labor_cost,
  coalesce(o.actual_hours, 0) * f.workshop_hourly_cost_snapshot as actual_labor_cost,
  greatest(f.gross_sale_amount - f.discount_amount, 0) * f.sales_commission_rate_snapshot / 100 as sales_commission,
  coalesce((
    select sum(abs(p.amount) * p.card_fee_rate_snapshot / 100)
    from public.order_payments p
    where p.order_id = o.id
      and p.status = 'posted'
      and p.amount > 0
      and p.method in ('debit_card', 'credit_card')
  ), 0) as card_fees,
  coalesce((select sum(p.amount) from public.order_payments p where p.order_id = o.id), 0) as paid_amount
from public.orders o
join public.order_financials f on f.order_id = o.id
left join public.order_cost_items ci on ci.order_id = o.id
group by o.id, o.order_sequence, f.order_id, f.gross_sale_amount, f.discount_amount,
  f.workshop_hourly_cost_snapshot, f.sales_commission_rate_snapshot;

